"""
Known-good record-keeping micro-app: FastAPI + SQLite, following the Workbench conventions.

You do NOT edit this file. Install it as <app>/main.py, then write <app>/fields.json next to it:

    {"title": "Trip checklist",
     "fields": [{"key": "item", "label": "Item", "type": "text"},
                {"key": "packed", "label": "Packed", "type": "checkbox"},
                {"key": "category", "label": "Category", "type": "select", "options": ["Documents", "Tech"]}]}

Run:  python -m uvicorn main:app --host 0.0.0.0 --port 8000      (workdir = the app directory)
Routes (JSON): GET /health, GET /fields, GET /items -> {"items":[...]}, POST /items (one object or {"items":[...]}),
PUT /items/{id} (partial), DELETE /items/{id}. /docs is accurate: every field is a typed property.
Publish as {"kind":"sheet"|"table","key":"id","rows_path":"items",...}.

Field types: text, number, currency, date (YYYY-MM-DD), checkbox, select (needs "options").
Data lives in ~/data/<slug of title>.db (the user's durable home). One real table `items` with one typed
column per field (TEXT / REAL / INTEGER), never a JSON blob, so it can be queried with plain SQL.
Adding a field to fields.json adds its column on the next start; existing rows keep NULL there.
"""

import json
import re
import sqlite3
from pathlib import Path
from typing import Any, Optional, Union

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field, create_model

DEFAULT_FIELDS = [
    {"key": "name", "label": "Name", "type": "text"},
    {"key": "quantity", "label": "Quantity", "type": "number"},
]
_cfg_path = Path(__file__).with_name("fields.json")
_cfg = json.loads(_cfg_path.read_text()) if _cfg_path.exists() else {}
TITLE = _cfg.get("title", "items")
FIELDS = [
    {"label": f["key"], "type": "text", **f} for f in (_cfg.get("fields") or DEFAULT_FIELDS)
]
for _f in FIELDS:
    assert re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", _f["key"]), "bad field key: " + repr(_f["key"])
    assert _f["type"] in ("text", "number", "currency", "date", "checkbox", "select"), "bad type: " + _f["type"]
COLUMNS = [f for f in FIELDS if f["key"] != "id"]  # `id` is the row key

DB = Path.home() / "data" / (re.sub(r"[^a-z0-9_]+", "_", TITLE.lower()).strip("_") or "items")
DB = DB.with_suffix(".db")
DB.parent.mkdir(parents=True, exist_ok=True)

SQL_TYPE = {"text": "TEXT", "number": "REAL", "currency": "REAL", "date": "TEXT", "checkbox": "INTEGER", "select": "TEXT"}
PY_TYPE = {"text": str, "number": Union[float, str], "currency": Union[float, str], "date": str,
           "checkbox": Union[bool, str], "select": str}


def _prop(f: dict[str, Any]) -> tuple[Any, Any]:
    hint = {"date": "YYYY-MM-DD", "checkbox": "true / false", "currency": "number, e.g. 12.5"}.get(f["type"], f["type"])
    if f["type"] == "select" and f.get("options"):
        hint = "one of: " + ", ".join(f["options"])
    extra = {"enum": list(f["options"])} if f["type"] == "select" and f.get("options") else {}
    if f["type"] == "date":
        extra = {"format": "date"}
    return Optional[PY_TYPE[f["type"]]], Field(None, title=f["label"], description=hint, json_schema_extra=extra or None)


_props = {f["key"]: _prop(f) for f in COLUMNS}
ItemIn = create_model("ItemIn", **_props)                       # a row as sent by a client (all optional)
Item = create_model("Item", id=(int, ...), **_props)            # a stored row
Payload = create_model("Payload", items=(Optional[list[ItemIn]], Field(None, description="bulk create")), **_props)


class ItemList(BaseModel):
    items: list[Item]  # type: ignore[valid-type]


app = FastAPI(title=TITLE, description="Fields: " + ", ".join(f["key"] + " (" + f["type"] + ")" for f in COLUMNS))


def con() -> sqlite3.Connection:
    c = sqlite3.connect(DB, timeout=10)
    c.row_factory = sqlite3.Row
    cols = "".join(', "' + f["key"] + '" ' + SQL_TYPE[f["type"]] for f in COLUMNS)
    c.execute("CREATE TABLE IF NOT EXISTS items (id INTEGER PRIMARY KEY AUTOINCREMENT" + cols + ")")
    have = {r["name"] for r in c.execute("PRAGMA table_info(items)")}
    for f in COLUMNS:  # a field added later becomes a new column
        if f["key"] not in have:
            c.execute('ALTER TABLE items ADD COLUMN "' + f["key"] + '" ' + SQL_TYPE[f["type"]])
    return c


def out_row(r: sqlite3.Row) -> dict[str, Any]:
    return {"id": r["id"], **{f["key"]: (bool(r[f["key"]]) if f["type"] == "checkbox" and r[f["key"]] is not None
                                          else r[f["key"]]) for f in COLUMNS}}


def clean(values: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for f in COLUMNS:
        k, t, v = f["key"], f["type"], values.get(f["key"])
        if v in (None, ""):
            out[k] = False if t == "checkbox" else None
            continue
        try:
            if t in ("number", "currency"):
                if isinstance(v, bool):
                    raise ValueError
                n = float(str(v).replace("$", "").replace(",", "").strip())
                out[k] = int(n) if n.is_integer() else n
            elif t == "checkbox":
                out[k] = v if isinstance(v, bool) else str(v).strip().lower() in ("true", "yes", "y", "1", "x")
            elif t == "date":
                if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(v)):
                    raise ValueError
                out[k] = str(v)
            elif t == "select" and f.get("options") and str(v) not in f["options"]:
                raise ValueError
            else:
                out[k] = str(v)
        except ValueError:
            raise HTTPException(422, f["label"] + ": " + repr(v) + " is not a valid " + t) from None
    return out


def _insert(c: sqlite3.Connection, data: dict[str, Any]) -> int:
    names = [f["key"] for f in COLUMNS]
    if not names:
        return c.execute("INSERT INTO items DEFAULT VALUES").lastrowid
    cols = ", ".join('"' + n + '"' for n in names)
    marks = ", ".join("?" for _ in names)
    return c.execute("INSERT INTO items (" + cols + ") VALUES (" + marks + ")", [data[n] for n in names]).lastrowid


@app.get("/health")
def health() -> dict[str, str]:
    return {"status": "ok"}


@app.get("/fields")
def fields() -> dict[str, Any]:
    """The field definitions (key, label, type, options). publish_app builds the sheet's columns from this."""
    return {"title": TITLE, "key": "id", "fields": FIELDS}


@app.get("/items", response_model=ItemList)
def list_items() -> dict[str, Any]:
    with con() as c:
        rows = c.execute("SELECT * FROM items ORDER BY id").fetchall()
    return {"items": [out_row(r) for r in rows]}


@app.post("/items", status_code=201, response_model=ItemList)
def create(body: Payload) -> dict[str, Any]:  # type: ignore[valid-type]
    """Create one row (the fields at the top level) or many (`{"items": [...]}`). All or nothing."""
    if body.items is not None:
        incoming = [r.model_dump() for r in body.items]
    else:
        incoming = [body.model_dump(exclude={"items"})]
    cleaned = [clean(r) for r in incoming]
    out = []
    with con() as c:
        for data in cleaned:
            out.append({"id": _insert(c, data), **data})
    return {"items": out}


@app.put("/items/{item_id}", response_model=Item)
def update(item_id: int, body: ItemIn) -> dict[str, Any]:  # type: ignore[valid-type]
    """Partial update: only the fields you send change."""
    with con() as c:
        row = c.execute("SELECT * FROM items WHERE id=?", (item_id,)).fetchone()
        if row is None:
            raise HTTPException(404, "item not found")
        data = clean({**out_row(row), **body.model_dump(exclude_unset=True)})
        if COLUMNS:
            sets = ", ".join('"' + f["key"] + '"=?' for f in COLUMNS)
            c.execute("UPDATE items SET " + sets + " WHERE id=?", [data[f["key"]] for f in COLUMNS] + [item_id])
    return {"id": item_id, **data}


@app.delete("/items/{item_id}", status_code=204)
def delete(item_id: int) -> None:
    with con() as c:
        c.execute("DELETE FROM items WHERE id=?", (item_id,))
